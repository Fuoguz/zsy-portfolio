import { writeFileSync } from "node:fs";

import { capabilities } from "../src/data/capabilities.js";
import { experience } from "../src/data/experience.js";
import { contentData } from "../src/data/index.js";
import { profile } from "../src/data/profile.js";
import { roleLenses } from "../src/data/role-lenses.js";
import {
  selectCapabilityEvidenceMap,
  selectPublicExperience,
  selectPublicProfile,
  selectPublicProjects,
  selectPublicRoleLenses,
  selectQuickProofs,
} from "../src/content/selectors.js";

const snapshot = {
  profile: selectPublicProfile(profile),
  roleLenses: selectPublicRoleLenses(roleLenses),
  projects: selectPublicProjects(contentData),
  quickProofs: selectQuickProofs(contentData),
  experience: selectPublicExperience(experience),
  capabilities: selectCapabilityEvidenceMap(capabilities, contentData),
};

const source = `// Generated by scripts/generate-public-content.js. Do not edit directly.\nexport const publicContent = Object.freeze(${JSON.stringify(snapshot, null, 2)});\n`;
writeFileSync("src/content/generated-public-data.js", source, "utf8");
console.log(`Public content snapshot generated (${snapshot.projects.length} projects, ${snapshot.capabilities.length} capabilities)`);
